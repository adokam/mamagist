function RootShell({ children }: { children: ReactNode }) {
  return (
    <html lang="en">
      <head>
        <HeadContent />
      </head>
      <body>
        {children}
        <Scripts />
      </body>
    </html>
  );
}

function RootComponent() {
  const { queryClient } = Route.useRouteContext();

  // Register the service worker once, in the browser only. It caches the app
  // shell and shows the offline page; it never caches health data or Supabase.
  useEffect(() => {
    const stopTheme = initTheme();
    return stopTheme;
  }, []);

  useEffect(() => {
    if ("serviceWorker" in navigator) {
      void navigator.serviceWorker.register("/sw.js").catch(() => {
        // Installable extras are a nice-to-have; the app works without them.
      });
    }
  }, []);

  return (
    <QueryClientProvider client={queryClient}>
      <AuthProvider>
        {/* App column: full width on phones, centered 430px column on bigger screens. */}
        <div className="mx-auto min-h-dvh w-full max-w-[430px] bg-background">
          {/* Required: nested routes render here. Removing <Outlet /> breaks all child routes. */}
          <Outlet />
        </div>
      </AuthProvider>
    </QueryClientProvider>
  );
}
